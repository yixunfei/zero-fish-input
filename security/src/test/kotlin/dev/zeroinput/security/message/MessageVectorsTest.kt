package dev.zeroinput.security.message

import java.security.SecureRandom
import java.util.Base64
import org.bouncycastle.crypto.digests.SHA256Digest
import org.bouncycastle.crypto.generators.Argon2BytesGenerator
import org.bouncycastle.crypto.generators.HKDFBytesGenerator
import org.bouncycastle.crypto.params.Argon2Parameters
import org.bouncycastle.crypto.params.HKDFParameters
import org.junit.Assert.*
import org.junit.Test

class MessageVectorsTest {
    private fun bytes(hex: String) = hex.chunked(2).map { it.toInt(16).toByte() }.toByteArray()
    private fun fixtures() = requireNotNull(javaClass.getResourceAsStream("/message/rustcrypto-v1.txt"))
        .bufferedReader().use { it.readLines() }

    @Test fun `all twelve cipher widths agree with independent RustCrypto GCM and XChaCha implementation`() {
        val rows = fixtures().filter { !it.startsWith('#') && it.isNotBlank() }
        assertEquals(12, rows.size)
        rows.forEach { row ->
            val values = row.split(',')
            val cipher = MessageCipher.fromId(values[0].toInt())
            val key = bytes(values[2]); val nonce = bytes(values[3]); val aad = bytes(values[4])
            val plain = bytes(values[5]); val expected = bytes(values[6])
            assertEquals(values[1].toInt(), key.size * 8)
            assertArrayEquals(expected, MessagePrimitives.aead(true, cipher, key, nonce, aad, plain))
            assertArrayEquals(plain, MessagePrimitives.aead(false, cipher, key, nonce, aad, expected))
        }
    }

    @Test fun `frozen single and six stage envelopes match independently generated bytes`() {
        for ((name, stages) in listOf("aes" to listOf(MessageStage(MessageCipher.AES)), "six" to MessageCipher.entries.map(::MessageStage))) {
            val random = object : SecureRandom() {
                var count = 0
                override fun nextBytes(bytes: ByteArray) { for (i in bytes.indices) bytes[i] = (count++).toByte() }
            }
            val crypto = MessageEnvelope(random, MessageKeys::argon)
            val shared = Base64.getUrlEncoder().withoutPadding().encodeToString(ByteArray(32) { it.toByte() })
            MessageCredential(MessageCredentialMode.RANDOM_KEY, shared.toCharArray()).use { credential ->
                val expected = bytes(fixtures().single { it.startsWith("# envelope-$name=") }.substringAfter('='))
                val actual = crypto.seal("public cover".toCharArray(), "public secret".toCharArray(), credential, stages, MessageKdf.NONE)
                assertArrayEquals(expected, actual)
                assertArrayEquals("public secret".toCharArray(), crypto.open("public cover".toCharArray(), expected, credential))
            }
        }
    }

    @Test fun `all three Argon2 profiles agree with RustCrypto`() {
        for ((name, profile) in listOf("standard" to MessageKdf.STANDARD, "increased" to MessageKdf.INCREASED,
            "high-memory" to MessageKdf.HIGH_MEMORY)) {
            val expected = bytes(fixtures().single { it.startsWith("# argon2id-$name=") }.substringAfter('='))
            assertArrayEquals(expected, MessageKeys.argon("public fixture passphrase".toByteArray(), ByteArray(16) { it.toByte() }, profile))
        }
    }

    @Test fun `five credential combinations and file digest match independent RustCrypto`() {
        val file = MessageKeyFile.factor(java.io.ByteArrayInputStream(ByteArray(128) { it.toByte() }))
        assertArrayEquals(bytes(fixtures().single { it.startsWith("# key-file-factor=") }.substringAfter('=')), file)
        for (mode in MessageCredentialMode.entries.filter { it.id in 1..5 }) {
            val text = when {
                mode == MessageCredentialMode.KEY_FILE -> ""
                mode.password -> "public fixture passphrase"
                else -> Base64.getUrlEncoder().withoutPadding().encodeToString(ByteArray(32) { it.toByte() })
            }
            MessageCredential(mode, text.toCharArray(), if (mode.file) file else null).use { credential ->
                val expected = bytes(fixtures().single { it.startsWith("# credential-root-${mode.id}=") }.substringAfter('='))
                val actual = MessageKeys.root(credential, ByteArray(16) { it.toByte() },
                    if (mode.password) MessageKdf.STANDARD else MessageKdf.NONE, true)
                assertArrayEquals(expected, actual)
                actual.fill(0)
            }
        }
        file.fill(0)
    }

    @Test fun `RFC 5869 SHA256 case one and RFC 9106 Argon2id vector match`() {
        val output = ByteArray(42)
        HKDFBytesGenerator(SHA256Digest()).apply {
            init(HKDFParameters(ByteArray(22) { 0x0b }, bytes("000102030405060708090a0b0c"), bytes("f0f1f2f3f4f5f6f7f8f9")))
        }.generateBytes(output, 0, output.size)
        assertArrayEquals(bytes("3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865"), output)
        val params = Argon2Parameters.Builder(Argon2Parameters.ARGON2_id).withVersion(19).withMemoryAsKB(32)
            .withIterations(3).withParallelism(4).withSalt(ByteArray(16) { 2 }).withSecret(ByteArray(8) { 3 })
            .withAdditional(ByteArray(12) { 4 }).build()
        val argon = ByteArray(32)
        Argon2BytesGenerator().apply { init(params) }.generateBytes(ByteArray(32) { 1 }, argon)
        assertArrayEquals(bytes("0d640df58d78766c08c037a34a8b53c9d01ef0452d75b65eb52520e96b01e659"), argon)
        params.clear()
    }

    @Test fun `NIST AES GCM empty and single block vectors match`() {
        val key = ByteArray(16); val nonce = ByteArray(12)
        assertArrayEquals(bytes("58e2fccefa7e3061367f1d57a4e7455a"),
            MessagePrimitives.aead(true, MessageCipher.AES, key, nonce, ByteArray(0), ByteArray(0)))
        assertArrayEquals(bytes("0388dace60b6a392f328c2b971b2fe78ab6e47d42cec13bdf53a67b21257bddf"),
            MessagePrimitives.aead(true, MessageCipher.AES, key, nonce, ByteArray(0), ByteArray(16)))
    }

    @Test fun `RFC 8998 SM4 GCM and IETF XChaCha AEAD published vectors match`() {
        // RFC 8998 appendix A.1.
        val sm4 = bytes("17f399f08c67d5ee19d0dc9969c4bb7d5fd46fd3756489069157b282bb200735" +
            "d82710ca5c22f0ccfa7cbf93d496ac15a56834cbcf98c397b4024a2691233b8d83de3541e4c2b58177e065a9bf7b62ec")
        assertArrayEquals(sm4, MessagePrimitives.aead(true, MessageCipher.SM4,
            bytes("0123456789abcdeffedcba9876543210"), bytes("00001234567800000000abcd"),
            bytes("feedfacedeadbeeffeedfacedeadbeefabaddad2"), bytes("aaaaaaaaaaaaaaaabbbbbbbbbbbbbbbb" +
                "ccccccccccccccccddddddddddddddddeeeeeeeeeeeeeeeeffffffffffffffffeeeeeeeeeeeeeeeeaaaaaaaaaaaaaaaa")))
        // draft-irtf-cfrg-xchacha-03 appendix A.3.1.
        val xchacha = bytes("bd6d179d3e83d43b9576579493c0e939572a1700252bfaccbed2902c21396cbb" +
            "731c7f1b0b4aa6440bf3a82f4eda7e39ae64c6708c54c216cb96b72e1213b452" +
            "2f8c9ba40db5d945b11b69b982c1bb9e3f3fac2bc369488f76b2383565d3fff9" +
            "21f9664c97637da9768812f615c68b13b52ec0875924c1c7987947deafd8780acf49")
        assertArrayEquals(xchacha, MessagePrimitives.aead(true, MessageCipher.XCHACHA20,
            ByteArray(32) { (0x80 + it).toByte() }, ByteArray(24) { (0x40 + it).toByte() },
            bytes("50515253c0c1c2c3c4c5c6c7"), ("Ladies and Gentlemen of the class of '99: If I could offer you only " +
                "one tip for the future, sunscreen would be it.").toByteArray(Charsets.US_ASCII)))
    }
}
